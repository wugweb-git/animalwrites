"""Write docs/component-map.md from the Kits registries and the code: each component with its classes, states, the
tokens it uses, and the files that use it. Run after changing a component: python3 tools/ci/component_map.py"""
import json, os, re, collections
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
items = []
for r in ("themes/kits-by-wugweb/kits-registry.json", "themes/animal-writes/kits-registry.json"):
    j = json.load(open(os.path.join(ROOT, r)))
    for it in j["items"]:
        it["owner"] = j["owner"]
        items.append(it)
used = collections.defaultdict(set)
for top in ("themes", "plugins"):
    for dp, _, fs in os.walk(os.path.join(ROOT, top)):
        for f in fs:
            if not f.endswith((".php", ".html", ".css", ".js")):
                continue
            p = os.path.join(dp, f)
            s = open(p, encoding="utf-8", errors="ignore").read()
            for c in set(re.findall(r"(?<![a-zA-Z0-9_-])((?:aw|kit)-[a-z0-9]+(?:-[a-z0-9]+)*)", s)):
                used[c].add(os.path.relpath(p, ROOT))
out = ["# Component map", "", "Generated by `tools/ci/component_map.py` from `kits-registry.json` (Kits master and Animal Writes) and the code. "
       "Accessibility and SEO records: Appearance → Kits system. Every state: the states sheet (/kits-demo/).", ""]
for kind in ("primitive", "component", "block", "pattern", "tool"):
    group = [i for i in items if i["type"] == kind]
    if not group:
        continue
    out += ["## " + kind.capitalize() + "s", "", "| Name | From | Classes or block | States | Tokens | Used in |", "|---|---|---|---|---|---|"]
    for i in group:
        files = sorted({f for p in i.get("classes", []) for c, fs in used.items() if c == p or c.startswith(p + "-") for f in fs})
        what = "`" + i["block"] + "`" if i.get("block") else " ".join("`" + c + "`" for c in i.get("classes", []))
        out.append("| %s | %s | %s | %s | %s | %s |" % (i["name"], i["owner"], what, ", ".join(i["states"]), ", ".join("`" + t + "`" for t in i.get("tokens", [])) or "—",
                                                     ("%d files: " % len(files) + ", ".join(f.split("/")[-1] for f in files[:6]) + (" …" if len(files) > 6 else "")) if files else "—"))
    out.append("")
open(os.path.join(ROOT, "docs/component-map.md"), "w").write("\n".join(out) + "\n")
print(len(items), "entries")
