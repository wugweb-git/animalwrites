#!/usr/bin/env python3
"""Responsive token engine: expand sparse sm/md/lg tokens, validate, emit CSS custom properties.

Contract: every token is {sm, md, lg}; sm is the base (min-width 0); md/lg inherit upward.
Usage: python3 tools/build-tokens.py  -> themes/animal-writes/tokens/tokens.compiled.json + assets/css/tokens.css
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "themes/animal-writes/tokens/tokens.json"
OUT_JSON = ROOT / "themes/animal-writes/tokens/tokens.compiled.json"
OUT_CSS = ROOT / "themes/animal-writes/assets/css/tokens.css"
BPS = ("sm", "md", "lg")


def expand(tok, name):
    if not isinstance(tok, dict) or "sm" not in tok:
        sys.exit(f"{name}: must be an object with an 'sm' value")
    bad = set(tok) - set(BPS)
    if bad:
        sys.exit(f"{name}: illegal breakpoint keys {bad} (only sm/md/lg)")
    out = {"sm": tok["sm"]}
    out["md"] = tok.get("md", out["sm"])
    out["lg"] = tok.get("lg", out["md"])
    return out


def resolve_refs(value, prims):
    def rep(m):
        group, key = m.group(1), m.group(2)
        try:
            return prims[group][key]
        except KeyError:
            sys.exit(f"unknown primitive {{{group}.{key}}}")
    return re.sub(r"\{(\w+)\.([\w-]+)\}", rep, str(value))


def main():
    src = json.loads(SRC.read_text())
    bp = src["$breakpoints"]
    if bp.get("sm") != 0 or not (bp["sm"] < bp["md"] < bp["lg"]) or set(bp) != set(BPS):
        sys.exit("$breakpoints must be sm=0 < md < lg")
    for name in src["tokens"]:
        if re.search(r"(mobile|tablet|desktop|phone)", name):
            sys.exit(f"{name}: device words are not allowed in token names")
    compiled = {n: expand(t, n) for n, t in src["tokens"].items()}
    compiled = {n: {b: resolve_refs(v, src["$primitives"]) for b, v in t.items()} for n, t in compiled.items()}
    assert {n: expand(t, n) for n, t in compiled.items()} == compiled, "expansion must be idempotent"
    OUT_JSON.write_text(json.dumps({"$breakpoints": bp, "tokens": compiled}, indent=2) + "\n")
    lines = ["/* Generated by tools/build-tokens.py from tokens/tokens.json. Do not edit. */", ":root {"]
    lines += [f"  --aw-{n}: {t['sm']};" for n, t in compiled.items()]
    lines.append("}")
    for b, prev in (("md", "sm"), ("lg", "md")):
        diff = [f"    --aw-{n}: {t[b]};" for n, t in compiled.items() if t[b] != t[prev]]
        if diff:
            lines += [f"@media (min-width: {bp[b]}px) {{", "  :root {", *diff, "  }", "}"]
    OUT_CSS.write_text("\n".join(lines) + "\n")
    print(f"{len(compiled)} tokens -> {OUT_CSS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
